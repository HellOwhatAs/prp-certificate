import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readRemoteParameters,parameterParts} from '../web/parameters.js';
const hash=b=>createHash('sha256').update(b).digest('hex');
const data=[Buffer.from('first proving chunk'),Buffer.from('second proving chunk'),Buffer.from('last proving chunk')];
const joined=Buffer.concat(data);
const info={pk_bytes:joined.length,pk_sha256:hash(joined),chunks:data.map((b,i)=>({file:`q1-${i}.dat`,bytes:b.length,sha256:hash(b)}))};
const parts=parameterParts(1,info),saved=new Map();let calls=[];
const cache={match:async k=>saved.get(k)?.clone(),put:async(k,r)=>saved.set(k,r.clone()),delete:async k=>saved.delete(k)};
const cacheStorage={open:async()=>cache};
const fetcher=async(url,options)=>{assert.equal(options.credentials,'same-origin');assert.equal(options.method,undefined);calls.push(url);const index=parts.findIndex(p=>p.url===url);return new Response(data[index],{headers:{'content-length':String(data[index].length)}});};
const read=opts=>readRemoteParameters(1,info,()=>{},{fetch:fetcher,cacheStorage,...opts});
assert.deepEqual(Buffer.from(await read()),joined);assert.equal(calls.length,3);
calls=[];assert.deepEqual(Buffer.from(await read({fetch:()=>{throw Error('offline');}})),joined);assert.equal(calls.length,0);
saved.set(parts[1].key,new Response(new Uint8Array(data[1].length)));
calls=[];assert.deepEqual(Buffer.from(await read()),joined);assert.deepEqual(calls,[parts[1].url]);
saved.delete(parts[2].key);calls=[];
await assert.rejects(()=>read({fetch:async()=>new Response('',{status:503})}));
assert.equal(saved.size,2);assert.deepEqual(Buffer.from(await read()),joined);assert.deepEqual(calls,[parts[2].url]);
assert.deepEqual(Buffer.from(await read({cacheStorage:{open:async()=>{throw Error('storage disabled');}}})),joined);
assert.deepEqual(Buffer.from(await read({cacheStorage:{open:async()=>({match:async()=>undefined,put:async()=>{throw Error('quota');}})}})),joined);
const single={...info,pk_bytes:data[0].length,chunks:[info.chunks[0]]};let attempts=0;
await assert.rejects(()=>readRemoteParameters(1,single,()=>{},{cacheStorage:{open:async()=>null},fetch:async()=>{attempts++;return new Response('',{status:401});}}),/刷新/);assert.equal(attempts,1);
await assert.rejects(()=>readRemoteParameters(1,single,()=>{},{cacheStorage:{open:async()=>null},fetch:async()=>new Response('x'.repeat(single.pk_bytes+1))}),/过大/);
assert.throws(()=>parameterParts(1,{...info,chunks:[{...info.chunks[0],file:'../secret'}]}));
assert.throws(()=>parameterParts(1,{...info,pk_bytes:info.pk_bytes-1}));
console.log('Cold download, offline cache, corrupt cache repair, interrupted resume, quota fallback, auth errors, byte bounds and manifest validation pass');
